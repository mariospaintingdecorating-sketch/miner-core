interface UiLanguageContextValue {
  readonly language: UiLanguage;
  readonly setLanguage: (language: UiLanguage) => void;
  readonly t: Translate;
}

const defaultContext: UiLanguageContextValue = {
  language: 'en',
  setLanguage: () => undefined,
  t: createTranslator('en'),
};

const UiLanguageContext = createContext<UiLanguageContextValue>(defaultContext);

export interface UiLanguageProviderProps {
  readonly children: ReactNode;
  readonly initialLanguage?: UiLanguage;
}

export function UiLanguageProvider({
  children,
  initialLanguage,
}: UiLanguageProviderProps) {
  const [language, setLanguageState] = useState<UiLanguage>(
    () => initialLanguage ?? storedLanguage() ?? resolveUiLanguage(),
  );
  const setLanguage = useCallback((nextLanguage: UiLanguage) => {
    setLanguageState(nextLanguage);

    try {
      globalThis.localStorage?.setItem(LANGUAGE_STORAGE_KEY, nextLanguage);
    } catch {
      // The interface can still switch language when local persistence is unavailable.
    }
  }, []);
  const value = useMemo<UiLanguageContextValue>(
    () => ({ language, setLanguage, t: createTranslator(language) }),
    [language, setLanguage],
  );

  useEffect(() => {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = language;
    }
  }, [language]);

  return (
    <UiLanguageContext.Provider value={value}>
      {children}
    </UiLanguageContext.Provider>
  );
}

export function useUiLanguage(): UiLanguageContextValue {
  return useContext(UiLanguageContext);
}

export function resolveUiLanguage(
  preferredLanguages: readonly string[] = systemLanguages(),
): UiLanguage {
  const primaryLanguage = (preferredLanguages[0] ?? '')
    .trim()
    .toLocaleLowerCase()
    .split(/[-_]/u)[0];

  if (
    primaryLanguage === 'pl' ||
    primaryLanguage === 'ru' ||
    primaryLanguage === 'en'
  ) {
    return primaryLanguage;
  }

  return 'en';
}

export function translate(
  language: UiLanguage,
  source: string,
  values?: TranslationValues,
): string {
  const template = language === 'en' ? source : messages[language][source] ?? source;

  return Object.entries(values ?? {}).reduce(
    (result, [key, value]) => result.split(`{${key}}`).join(String(value)),
    template,
  );
}

function createTranslator(language: UiLanguage): Translate {
  return (source, values) => translate(language, source, values);
}

function storedLanguage(): UiLanguage | null {
  try {
    const stored = globalThis.localStorage?.getItem(LANGUAGE_STORAGE_KEY);
    return stored === 'pl' || stored === 'ru' || stored === 'en' ? stored : null;
  } catch {
    return null;
  }
}

function systemLanguages(): readonly string[] {
  if (typeof navigator === 'undefined') {
    return [];
  }

  return navigator.languages.length > 0
    ? navigator.languages
    : [navigator.language];
}
